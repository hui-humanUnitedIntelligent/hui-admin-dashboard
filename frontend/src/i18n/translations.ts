/** Validierung: Prüft ob beide Sprachen dieselben Keys haben */
export function validateTranslations(): { missing_en: string[]; missing_de: string[] } {
  const de_keys = new Set(Object.keys(translations.de));
  const en_keys = new Set(Object.keys(translations.en));
  return {
    missing_en: [...de_keys].filter(k => !en_keys.has(k)),
    missing_de: [...en_keys].filter(k => !de_keys.has(k)),
  };
}
